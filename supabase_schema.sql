  title text not null,
  date date not null,
  time time,
  type text, -- 'Local', 'Sede', etc.
  focus text,
  description text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
alter table public.events enable row level security;
create policy "Users can CRUD their own events." on events for all using (auth.uid() = user_id);

